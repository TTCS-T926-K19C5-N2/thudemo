import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
const require = createRequire(import.meta.url);
const { chromium } = require('playwright');
const root = resolve(import.meta.dirname, '../../..');
const runId = process.env.AI_REMEDIATION_RUN_ID;
assert.match(runId ?? '', /^\d{8}T\d{6}-remediation$/);
const cacheDir = resolve(root, '.cache/ai-remediation', runId);
const evidenceDir = resolve(root, 'evidence/ai-remediation', runId);
const fixture = JSON.parse(readFileSync(resolve(cacheDir, 'r19-fixture.json'), 'utf8'));
assert.equal(fixture.runId, runId);
assert.equal(fixture.ticketCount, 5000);
mkdirSync(evidenceDir, { recursive: true });
const profileDir = resolve(cacheDir, 'r19-5000-browser-profile');
const report = { runId, environment: 'Authenticated Chromium; isolated local app/PostgreSQL on loopback. No 4G throttling or physical device.', workload: { paidTickets: 5000, repetitions: 1 }, rawLatencyMs: [], pageErrors: [], screenshots: [] };
let context;
try {
  context = await chromium.launchPersistentContext(profileDir, { headless: true, viewport: { width: 1440, height: 1000 }, serviceWorkers: 'allow' });
  await context.addCookies([{ name: 'event_session', value: fixture.token, url: 'http://127.0.0.1:3410', expires: Math.floor(Date.now() / 1000) + 4 * 60 * 60, httpOnly: true, sameSite: 'Lax' }]);
  const page = context.pages()[0] ?? await context.newPage();
  page.on('pageerror', (error) => report.pageErrors.push(error.message));
  await page.goto('http://127.0.0.1:3410/scanner/snapshot', { waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Vào máy quét suất này' }).click();
  const started = performance.now();
  const fullResponsePromise = page.waitForResponse((response) => response.request().method() === 'GET' && new URL(response.url()).pathname.endsWith('/tickets') && !new URL(response.url()).searchParams.has('since'), { timeout: 30000 });
  await page.getByRole('button', { name: /^Tải danh sách$/ }).click();
  await page.getByText('Đã tải mới nhất', { exact: true }).waitFor({ timeout: 30000 });
  const fullResponse = await fullResponsePromise;
  const completed = performance.now();
  const body = await fullResponse.json();
  const elapsed = Number((completed - started).toFixed(3));
  report.rawLatencyMs = [elapsed];
  report.p95Ms = elapsed;
  report.maxMs = elapsed;
  report.errorRate = fullResponse.status() >= 400 ? 1 : 0;
  report.serverResponseStatus = fullResponse.status();
  report.snapshot = { mode: body.mode, totalTickets: body.totalTickets, returnedRecords: body.tickets?.length ?? 0, rawJsonBytes: Buffer.byteLength(JSON.stringify(body)), cursorPresent: Boolean(body.cursor) };
  const local = await page.evaluate(async (showtimeId) => {
    const request = indexedDB.open('thudemo_scanner_db');
    const db = await new Promise((resolve, reject) => { request.onerror = () => reject(request.error); request.onsuccess = () => resolve(request.result); });
    return await new Promise((resolve, reject) => {
      const tx = db.transaction(['showtime_meta', 'tickets'], 'readonly');
      const metaReq = tx.objectStore('showtime_meta').get(showtimeId);
      const ticketsReq = tx.objectStore('tickets').index('showtimeId').getAll(showtimeId);
      tx.oncomplete = () => resolve({ meta: metaReq.result, tickets: ticketsReq.result });
      tx.onerror = () => reject(tx.error);
    });
  }, fixture.showtimeId);
  const keys = Object.keys(local.tickets[0] ?? {}).sort();
  const forbiddenFields = keys.filter((key) => /name|email|phone|customer|holder/i.test(key));
  const containsSyntheticPII = JSON.stringify(local.tickets).includes('@r19-fixture.invalid') || JSON.stringify(local.tickets).includes('R19 Synthetic Scanner');
  report.local = { count: local.tickets.length, keys, allCodesPresent: local.tickets.every((ticket) => typeof ticket.code === 'string'), allStatusesPresent: local.tickets.every((ticket) => typeof ticket.status === 'string'), forbiddenFieldNames: forbiddenFields, containsSyntheticPII, metaStatus: local.meta?.status, ticketCount: local.meta?.ticketCount };
  assert.equal(fullResponse.status(), 200);
  assert.equal(body.mode, 'full');
  assert.equal(body.totalTickets, 5000);
  assert.equal(local.tickets.length, 5000);
  assert.equal(local.meta?.ticketCount, 5000);
  assert.deepEqual(forbiddenFields, []);
  assert.equal(containsSyntheticPII, false);
  assert.equal(report.pageErrors.length, 0);
  await page.screenshot({ path: resolve(evidenceDir, 'r19-5000-desktop.png'), fullPage: true, animations: 'disabled' });
  report.screenshots.push('r19-5000-desktop.png');
  await page.setViewportSize({ width: 390, height: 844 });
  report.mobileNoOverflow = await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
  assert.equal(report.mobileNoOverflow, true);
  await page.screenshot({ path: resolve(evidenceDir, 'r19-5000-mobile.png'), fullPage: true, animations: 'disabled' });
  report.screenshots.push('r19-5000-mobile.png');
  report.localNetworkOnly = true;
  writeFileSync(resolve(evidenceDir, 'r19-5000-browser.json'), JSON.stringify(report, null, 2) + '\n');
  console.log(`R19 5000-ticket local browser measurement completed in ${elapsed} ms; evidence saved in ${evidenceDir}.`);
} catch (error) {
  report.failure = error instanceof Error ? error.message : String(error);
  writeFileSync(resolve(evidenceDir, 'r19-5000-browser.json'), JSON.stringify(report, null, 2) + '\n');
  throw error;
} finally {
  await context?.close();
}
