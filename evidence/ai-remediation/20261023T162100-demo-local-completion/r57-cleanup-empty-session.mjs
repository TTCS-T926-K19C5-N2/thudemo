import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const req = createRequire(`${process.cwd()}/apps/api/package.json`);
const { PrismaClient } = req('@prisma/client');
const { PrismaPg } = req('@prisma/adapter-pg');
const c = JSON.parse(readFileSync('D:/Merge_2/Codegym-demo-proof-20261023T1530/.sprint1-demo/config.json', 'utf8'));
const a = c.accounts.find((x) => x.name === 'buyer' && x.roles.includes('BUYER'));
const url = new URL(`postgresql://${encodeURIComponent(c.user)}:${encodeURIComponent(c.dbPassword)}@127.0.0.1:${c.ports.postgres}/${c.database}`);
if (!/^s1demo-[a-f0-9]{12}$/.test(c.profile) || c.database !== `sprint1_demo_${c.profile.slice(7)}` || url.hostname !== '127.0.0.1' || url.port !== String(c.ports.postgres)) throw new Error('Profile guard failed');
const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: url.toString(), max: 2 }) });
const user = await db.user.findUnique({ where: { email: a.email }, select: { id: true } });
if (!user) throw new Error('Synthetic user not found');
const showtimeId = '914556a8-ba19-4766-9e20-00a3d93df432';
const cutoff = new Date(Date.now() - 20 * 60 * 1000);
const sessions = await db.holdSession.findMany({ where: { userId: user.id, showtimeId, createdAt: { gte: cutoff }, orders: { none: {} }, seats: { none: {} } }, select: { id: true, createdAt: true } });
const before = await db.holdSession.count({ where: { showtimeId } });
for (const s of sessions) await db.holdSession.deleteMany({ where: { id: s.id, userId: user.id, showtimeId, createdAt: s.createdAt, orders: { none: {} }, seats: { none: {} } } });
const after = await db.holdSession.count({ where: { showtimeId } });
const holds = await db.seatHold.count({ where: { showtimeId } });
const result = { profile: c.profile, syntheticUserMatched: true, candidateCount: sessions.length, deletedCount: before - after, holdsAfter: holds, sessionCountBefore: before, sessionCountAfter: after, guardedNoOrderNoSeats: true };
writeFileSync('D:/Merge_2/Codegym/evidence/ai-remediation/20261023T162100-demo-local-completion/r57-cleanup-verification.json', `${JSON.stringify(result, null, 2)}\n`);
await db.$disconnect();
console.log(JSON.stringify(result));
